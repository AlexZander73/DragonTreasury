import { cpSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';

const candidates = [process.env.MAIN_WEBSITE_ROOT, resolve('../..'), resolve('../MainWebsite')].filter(Boolean);
const root = candidates.find(path => existsSync(resolve(path, 'data/showcase.json')));
if (!root) throw new Error('Set MAIN_WEBSITE_ROOT to the MainWebsite checkout containing data/showcase.json.');
if (!existsSync('dist/index.html')) throw new Error('Run npm run build first.');
const destination = resolve(root, 'projects/DragonTreasury');
mkdirSync(destination, { recursive: true });
// This directory is generated by Vite; discard obsolete content-hashed bundles.
rmSync(resolve(destination, 'assets'), { recursive: true, force: true });
cpSync(resolve('dist'), destination, { recursive: true });
console.log(`Exported Dragon Treasury to ${destination}. The catalog stays in ${root}/data/showcase.json.`);
